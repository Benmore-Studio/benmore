// gitEnsureRepo initializes the app dir as a git repo if it isn't
// already one, writes .gitignore, and creates the initial commit.
// Idempotent - safe to call on every write.
func gitEnsureRepo(dir, displayName string) error {
	mu := gitDirLock(dir)
	mu.Lock()
	defer mu.Unlock()
	return gitEnsureRepoLocked(dir, displayName)
}

func gitEnsureRepoLocked(dir, displayName string) error {
	if !gitAvailable() || dir == "" {
		return fmt.Errorf("git history unavailable: git and an app directory are required")
	}
	if err := gitProtectHistory(dir); err != nil {
		return err
	}
	exists, err := gitAppRepoExists(dir)
	if err != nil || exists {
		return err
	}
	if _, err := gitRun(dir, "init", "-q", "-b", "main"); err != nil {
		return fmt.Errorf("git init: %w", err)
	}
	// Local identity; every configuration write must succeed before staging.
	for _, setting := range [][2]string{{"user.email", "benmore@localhost"}, {"user.name", "Benmore"}, {"commit.gpgsign", "false"}} {
		if _, err := gitRun(dir, "config", setting[0], setting[1]); err != nil {
			return err
		}
	}
	if err := gitStageSource(dir); err != nil {
		return err
	}
	msg := "Initial commit"
	if displayName != "" {
		msg = "Initial commit: " + displayName
	}
	if _, err := gitRun(dir, "commit", "-q", "--allow-empty", "-m", msg); err != nil {
		return fmt.Errorf("git commit (initial): %w", err)
	}
	return nil
}

// gitPostCommitHook, when non-nil, is invoked after a commit lands in
// an app repo. It MUST be cheap and non-blocking (it runs on the write
// path, under the per-dir lock) - the platform edition points it at
// the GitHub sync notifier (platform_github.go), which only resets a
// debounce timer; the actual push happens on a background goroutine.
// nil in the framework/cloud editions.
var gitPostCommitHook func(dir string)

// gitPostRewriteHook fires after a HISTORY REWRITE (gitHardRestore's
// reset --hard). The mirror syncs again; it never forces on its own
// (githubNotifyRewrite).
var gitPostRewriteHook func(dir string)

// gitAutoCommit commits only source files, returning failures to the caller.
// A clean source tree is a successful no-op; protected untracked files don't
// make a snapshot dirty even if a nested ignore file tries to include them.
func gitAutoCommit(dir, msg string) error {
	mu := gitDirLock(dir)
	mu.Lock()
	defer mu.Unlock()
	return gitAutoCommitLocked(dir, msg)
}

func gitAutoCommitLocked(dir, msg string) error {
	if err := gitEnsureRepoLocked(dir, ""); err != nil {
		return err
	}
	if err := gitStageSource(dir); err != nil {
		return err
	}
	out, err := gitRun(dir, "diff", "--cached", "--name-only", "-z")
	if err != nil {
		return err
	}
	if out == "" {
		return nil
	}
	if _, err := gitRun(dir, "commit", "-q", "-m", msg); err != nil {
		return err
	}
	if gitPostCommitHook != nil {
		gitPostCommitHook(dir)
	}
	return nil
}

// Snapshot source and inspect HEAD under one per-app git lock. Callers still
// coordinate source mutations separately; this lock serializes git operations.
func gitSnapshotHeadChecked(dir, msg string) (string, error) {
	mu := gitDirLock(dir)
	mu.Lock()
	defer mu.Unlock()
	if err := gitAutoCommitLocked(dir, msg); err != nil {
		return "", err
	}
	sha, err := gitSafeCommit(dir, "HEAD")
	if err != nil {
		return "", err
	}
	changed, err := gitRun(dir, "diff", "--name-only", "-z", sha, "--")
	if err != nil {
		return "", err
	}
	untracked, err := gitSourcePaths(dir, "--others", "--exclude-standard")
	if err != nil {
		return "", err
	}
	if changed != "" || untracked != "" {
		return "", fmt.Errorf("source changed during git snapshot")
	}
	return sha, nil
}

func gitSnapshotHead(dir, msg string) (string, bool) {
	sha, err := gitSnapshotHeadChecked(dir, msg)
	return sha, err == nil
}

// gitHeadShortSha returns the short HEAD sha of dir's per-app repo, or "" when
// there's no repo / no commits. Best-effort, read-only - used for status
// display (dev and prod are SEPARATE repos, so their shas are not comparable
// across instances; this is informational context only).
func gitHeadShortSha(dir string) string {
	if !gitAvailable() || dir == "" {
		return ""
	}
	out, err := gitRun(dir, "rev-parse", "--short", "HEAD")
	if err != nil {
		return ""
	}
	return strings.TrimSpace(out)
}

// gitHardRestore resets dir's TRACKED files back to sha (a value previously
// returned by gitSnapshotHead). Used to roll a destination back after a failed
// or partial overwrite. Gitignored paths (data.db, uploads/, .benmore/) are NOT
// touched. New untracked source files remain and may need manual cleanup.
func gitHardRestore(dir, sha string) error {
	if !gitAvailable() || dir == "" || sha == "" {
		return fmt.Errorf("git restore requires git, an app directory and a commit")
	}
	mu := gitDirLock(dir)
	mu.Lock()
	defer mu.Unlock()
	sha, err := gitValidateRestore(dir, sha)
	if err != nil {
		return err
	}
	_, err = gitRun(dir, "reset", "--hard", sha)
	if err == nil && gitPostRewriteHook != nil {
		gitPostRewriteHook(dir)
	}
	return err
}

// GitCommit is the read shape returned by gitLog. Mirrors `git log
// --format=%H|%h|%an|%ad|%s` parsed back into a typed record so
// callers don't have to deal with the raw `git` stdout.
type GitCommit struct {
	SHA      string `json:"sha"`
	ShortSHA string `json:"short_sha"`
	Author   string `json:"author"`
	AuthorAt string `json:"author_at"`
	Message  string `json:"message"`
	NumFiles int    `json:"files_changed"`
}

// gitLog returns the last `limit` commits, newest first. limit <= 0
// uses a sane default (50). Empty result for an uninitialized repo -
// not an error, just an honest "no history yet".
func gitLog(dir string, limit int) ([]GitCommit, error) {
	if !gitAvailable() {
		return nil, fmt.Errorf("git: binary not installed on host")
	}
	if _, err := os.Stat(filepath.Join(dir, ".git")); err != nil {
		return nil, nil
	}
	if limit <= 0 {
		limit = 50
	}
	// `%x1f` is ASCII unit separator - safe inside commit messages
	// (commits never contain it; commas/pipes/newlines do).
	const sep = "\x1f"
	out, err := gitRun(dir, "log", "-n", strconv.Itoa(limit),
		"--pretty=format:%H"+sep+"%h"+sep+"%an"+sep+"%ad"+sep+"%s",
		"--date=iso-strict")
	if err != nil {
		return nil, err
	}
	var commits []GitCommit
	for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
		if line == "" {
			continue
		}
		parts := strings.SplitN(line, sep, 5)
		if len(parts) < 5 {
			continue
		}
		commit := GitCommit{
			SHA: parts[0], ShortSHA: parts[1], Author: parts[2],
			AuthorAt: parts[3], Message: parts[4],
		}
		// Fetch the file-change count cheaply via `git show --stat`.
		// Cap at one extra exec per row - for a 50-row log that's
		// ~50ms total, which is fine. Drop in a future pass if it
		// becomes a bottleneck (could parse from --numstat in the
		// main log call).
		if stat, err := gitRun(dir, "show", "--stat", "--format=", parts[0]); err == nil {
			commit.NumFiles = countStatFiles(stat)
		}
		commits = append(commits, commit)
	}
	return commits, nil
}

// gitShow returns the unified diff for a single commit. Short SHAs, HEAD,
// and HEAD~N all work. The caller's value is resolved to a commit id behind
// --end-of-options first, so it is only ever a revision: passed straight to
// `git show` (router process, viewer-level tool), a value starting with "-"
// would be parsed as a git option instead.
func gitShow(dir, sha string) (string, error) {
	if !gitAvailable() {
		return "", fmt.Errorf("git: binary not installed on host")
	}
	if sha == "" {
		return "", fmt.Errorf("git: sha is required")
	}
	resolved, err := gitRun(dir, "rev-parse", "--verify", "--quiet", "--end-of-options", sha+"^{commit}")
	if err != nil {
		return "", fmt.Errorf("git: unknown commit %q", sha)
	}
	// Every caller shows a few hundred KB at most; a commit that adds a huge
	// text file must not be buffered whole in the router.
	out, _, err := gitRunCapped(dir, gitShowMaxBytes, "show", strings.TrimSpace(resolved))
	return out, err
}

// gitShowMaxBytes bounds the diff gitShow returns.
const gitShowMaxBytes = 1 << 20

// gitRevert makes the working tree match `sha` exactly and records a
// NEW commit on top of HEAD. This is the safe form of "go back to
// that version" - history is preserved, never rewritten.
//
// Implementation: `git read-tree --reset -u <sha>` resets the index
// AND the working tree to match `sha` (without touching HEAD or the
// reflog). Files added in commits between `sha` and HEAD are deleted
// from the working tree; files deleted in that range are restored;
// files modified are reset to their `sha` content. Then a normal
// commit records the new HEAD pointing at the rolled-back tree.
//
// The naive `git checkout <sha> -- .` we used earlier only restored
// files that existed in <sha> and silently left newer files alone -
// the revert looked correct in `git log` but the working tree still
// had the post-edit files. read-tree --reset is the correct primitive.
func gitRevert(dir, sha string) (GitCommit, error) {
	if !gitAvailable() {
		return GitCommit{}, fmt.Errorf("git: binary not installed on host")
	}
	mu := gitDirLock(dir)
	mu.Lock()
	defer mu.Unlock()

	target, err := gitValidateRestore(dir, sha)
	if err != nil {
		return GitCommit{}, err
	}
	if _, err := gitRun(dir, "read-tree", "--reset", "-u", target); err != nil {
		return GitCommit{}, fmt.Errorf("git read-tree: %w", err)
	}
	msg := fmt.Sprintf("revert to %s", sha)
	if _, err := gitRun(dir, "commit", "-q", "--allow-empty", "-m", msg); err != nil {
		return GitCommit{}, fmt.Errorf("git commit (revert): %w", err)
	}
	// A revert is a FORWARD commit (nothing rewound), so the mirror
	// push stays fast-forward - notify like any other commit.
	if gitPostCommitHook != nil {
		gitPostCommitHook(dir)
	}
	// Return the freshly-created HEAD as the caller's confirmation.
	commits, err := gitLog(dir, 1)
	if err != nil || len(commits) == 0 {
		return GitCommit{SHA: "HEAD", Message: msg, AuthorAt: time.Now().UTC().Format(time.RFC3339)}, nil
	}
	return commits[0], nil
}

// gitRun is the low-level exec helper. Captures combined stdout/stderr
// (git's user-facing output sometimes goes to stderr) and returns it
// as a string. err is non-nil if git exited non-zero.
//
// `-c safe.directory=<dir>` is prepended on every invocation. The
// production deploy chowns app directories to a per-app DynamicUser
// after the framework writes the initial scaffold, so the router
// process (running as the platform user) and the .git directory
// (owned by the per-app user) belong to different uids. Git's
// 2.35+ "dubious ownership" check would otherwise refuse to operate
// on the repo at all. safe.directory tells git "yes I know, run it
// anyway" for this specific path - narrower than the global `*`
// allowlist, scoped to one operation at a time.
func gitRun(dir string, args ...string) (string, error) {
	return gitRunInput(dir, "", args...)
}

// gitHardenedArgs prefixes every router-side git invocation on an app repo.
// safe.directory is needed because the repo belongs to another user, and it
// also makes git trust that repo's .git/config. That config is tenant-adjacent
// state, so neutralize every setting that can execute a program or redirect
// credentials, even though the file tools refuse .git/ writes: a single
// missed write path must not become code execution as the router.
func gitHardenedArgs(dir string) []string {
	return []string{
		"-c", "safe.directory=" + dir,
		"-c", "core.fsmonitor=false",
		"-c", "core.hooksPath=/dev/null",
		"-c", "core.sshCommand=false",
		"-c", "core.pager=cat",
		"-c", "core.editor=false",
		"-c", "sequence.editor=false",
		"-c", "diff.external=",
		"-c", "commit.gpgSign=false",
		"-c", "tag.gpgSign=false",
		"-c", "push.gpgSign=false",
		"-c", "credential.helper=",
		"-c", "protocol.ext.allow=never",
	}
}

// gitAllowedLocalConfig is every key a Benmore-created app repo carries: the
// defaults `git init` writes plus the identity gitEnsureRepoLocked sets. The
// tenant's uid owns .git/config, and .gitattributes is ordinary app source, so
// any other key (filter.*.clean, diff.*.textconv, include.path, core.gitProxy,
// ...) could run a program of the tenant's choosing as the router. -c flags
// cannot neutralize driver names they do not know, so the config is audited.
var gitAllowedLocalConfig = map[string]bool{
	"core.repositoryformatversion": true, "core.filemode": true, "core.bare": true,
	"core.logallrefupdates": true, "core.ignorecase": true, "core.precomposeunicode": true,
	"core.symlinks": true, "user.email": true, "user.name": true, "commit.gpgsign": true,
	"extensions.refstorage": true, "extensions.objectformat": true,
}

// gitAuditLocalConfig refuses to run git in a repo whose local config holds
// any setting outside the allowlist. Reading the config executes nothing.
func gitAuditLocalConfig(dir string) error {
	if _, err := os.Lstat(filepath.Join(dir, ".git")); err != nil {
		return nil // no repo yet (init) or unreadable: git itself reports it
	}
	if err := gitAuditRepoLayout(dir); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), gitCommandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, "git", append(gitHardenedArgs(dir), "config", "--local", "--list", "-z", "--name-only")...)
	cmd.Dir = dir
	cmd.Env = gitCommandEnv()
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("git config audit: %w", err)
	}
	for _, key := range strings.Split(string(out), "\x00") {
		if key != "" && !gitAllowedLocalConfig[strings.ToLower(key)] {
			return fmt.Errorf("app git config contains an unsupported setting; operator cleanup is required before history operations")
		}
	}
	return nil
}

// gitAuditRepoLayout refuses a repository whose metadata sends git outside
// this app's own .git directory. The router's uid can read and write every
// tenant tree, and the tenant owns its .git, so a .git file or symlink, a
// commondir file, object alternates, or a symlinked ref, object or pack
// directory would point the router's git at another tenant's repository:
// its history shows on this app's dashboard, a revert copies its files into
// this app, a commit lands in its refs, and a GitHub push mirrors it - while
// the config audit reads that repository's clean config. Git itself creates
// none of these in a Benmore repo. Reading the layout executes nothing.
func gitAuditRepoLayout(dir string) error {
	refuse := func() error {
		return fmt.Errorf("app git metadata points outside the app's own repository; operator cleanup is required before history operations")
	}
	gitDir := filepath.Join(dir, ".git")
	info, err := os.Lstat(gitDir)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return refuse()
	}
	for _, name := range []string{"commondir", "gitdir", filepath.Join("objects", "info", "alternates"), filepath.Join("objects", "info", "http-alternates")} {
		if _, err := os.Lstat(filepath.Join(gitDir, name)); err == nil {
			return refuse()
		} else if !os.IsNotExist(err) {
			return refuse()
		}
	}
	// No symlink at the top of .git, among the object fan-out and pack
	// entries, in reftable, or anywhere under refs/.
	for _, sub := range []string{"", "objects", filepath.Join("objects", "pack"), filepath.Join("objects", "info"), "reftable"} {
		entries, err := os.ReadDir(filepath.Join(gitDir, sub))
		if err != nil {
			if os.IsNotExist(err) && sub != "" {
				continue
			}
			return refuse()
		}
		for _, e := range entries {
			if e.Type()&os.ModeSymlink != 0 {
				return refuse()
			}
		}
	}
	err = filepath.WalkDir(filepath.Join(gitDir, "refs"), func(_ string, d os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if d.Type()&os.ModeSymlink != 0 {
			return fs.ErrPermission
		}
		return nil
	})
	if err != nil {
		return refuse()
	}
	return nil
}

// gitCommandTimeout bounds one router-side git invocation on a tenant repo. A
// wedged git (stale lock, pathological repo) would otherwise hold its request
// goroutine and the per-app git mutex indefinitely.
const gitCommandTimeout = 5 * time.Minute

func gitRunInput(dir, input string, args ...string) (string, error) {
	if err := gitAuditLocalConfig(dir); err != nil {
		return "", err
	}
	full := append(gitHardenedArgs(dir), args...)
	ctx, cancel := context.WithTimeout(context.Background(), gitCommandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, "git", full...)
	cmd.Dir = dir
	cmd.Env = gitCommandEnv()
	cmd.Stdin = strings.NewReader(input)
	var buf bytes.Buffer
	cmd.Stdout = &buf
	cmd.Stderr = &buf
	if err := cmd.Run(); err != nil {
		return buf.String(), fmt.Errorf("git %s: %w (%s)", strings.Join(args, " "), err, strings.TrimSpace(buf.String()))
	}
	return buf.String(), nil
}

// cappedBuffer keeps the first limit bytes and, once full, cancels the command
// that feeds it instead of buffering the rest.
type cappedBuffer struct {
	buf       bytes.Buffer
	limit     int
	cancel    context.CancelFunc
	truncated bool
}

func (c *cappedBuffer) Write(p []byte) (int, error) {
	room := c.limit - c.buf.Len()
	if room > 0 {
		if len(p) <= room {
			c.buf.Write(p)
			return len(p), nil
		}
		c.buf.Write(p[:room])
	}
	c.truncated = true
	c.cancel()
	return len(p), nil
}

// gitRunCapped runs git and returns at most limit bytes of its output (the
// process is stopped once the limit is reached). truncated reports that output
// was cut.
func gitRunCapped(dir string, limit int, args ...string) (out string, truncated bool, err error) {
	full := append(gitHardenedArgs(dir), args...)
	ctx, cancel := context.WithTimeout(context.Background(), gitCommandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, "git", full...)
	cmd.Dir = dir
	cmd.Env = gitCommandEnv()
	cmd.Stdin = strings.NewReader("")
	cb := &cappedBuffer{limit: limit, cancel: cancel}
	cmd.Stdout = cb
	cmd.Stderr = cb
	runErr := cmd.Run()
	if cb.truncated {
		return cb.buf.String(), true, nil // stopped by us on purpose
	}
	if runErr != nil {
		return cb.buf.String(), false, fmt.Errorf("git %s: %w (%s)", strings.Join(args, " "), runErr, strings.TrimSpace(cb.buf.String()))
	}
	return cb.buf.String(), false, nil
}

// Keep command selection and config independent of inherited repository/index
// overrides. The push path adds its own scoped askpass credentials afterward.
func gitCommandEnv() []string {
	env := []string{}
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "HOME=") || strings.HasPrefix(kv, "XDG_CONFIG_HOME=") || strings.HasPrefix(kv, "GIT_") {
			continue
		}
		env = append(env, kv)
	}
	return append(env, "HOME=/tmp", "XDG_CONFIG_HOME=/tmp", "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_TERMINAL_PROMPT=0", "GIT_OPTIONAL_LOCKS=0")
}

func gitValidateRestore(dir, sha string) (string, error) {
	if exists, err := gitAppRepoExists(dir); err != nil {
		return "", err
	} else if !exists {
		return "", fmt.Errorf("app has no git repository")
	}
	if err := gitCheckCurrentTree(dir); err != nil {
		return "", err
	}
	target, err := gitSafeCommit(dir, sha)
	if err != nil {
		return "", err
	}
	return target, gitCheckRestoreObstructions(dir, target)
}

// countStatFiles parses the trailing "N files changed" summary from
// `git show --stat`. Returns 0 when no summary line is present
// (single-file commits omit the count in older git versions).
func countStatFiles(stat string) int {
	for _, line := range strings.Split(stat, "\n") {
		line = strings.TrimSpace(line)
		// Examples:
		//   "1 file changed, 1 insertion(+)"
		//   "5 files changed, 12 insertions(+), 3 deletions(-)"
		if idx := strings.Index(line, " file"); idx > 0 {
			n, err := strconv.Atoi(strings.TrimSpace(line[:idx]))
			if err == nil {
				return n
			}
		}
	}
	// Fallback: count diff stat lines (each starts with a filename).
	n := 0
	for _, line := range strings.Split(stat, "\n") {
		if strings.Contains(line, "|") {
			n++
		}
	}
	return n
}
