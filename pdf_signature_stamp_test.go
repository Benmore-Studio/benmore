func stampPDFObjects(objects []string) []byte {
	var b bytes.Buffer
	b.WriteString("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n")
	offsets := make([]int, len(objects)+1)
	for i, obj := range objects {
		offsets[i+1] = b.Len()
		fmt.Fprintf(&b, "%d 0 obj\n%s\nendobj\n", i+1, obj)
	}
	xref := b.Len()
	fmt.Fprintf(&b, "xref\n0 %d\n0000000000 65535 f \n", len(offsets))
	for _, offset := range offsets[1:] {
		fmt.Fprintf(&b, "%010d 00000 n \n", offset)
	}
	fmt.Fprintf(&b, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(offsets), xref)
	return b.Bytes()
}

func stampFixturePNG(t *testing.T, width, height int) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.SetRGBA(x, y, color.RGBA{R: 255, A: 255})
		}
	}
	var b bytes.Buffer
	if err := png.Encode(&b, img); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

func TestStampPDFSignaturesMultipageCropAndRotation(t *testing.T) {
	source := stampFixturePDF()
	sourceBefore := append([]byte(nil), source...)
	signature := stampFixturePNG(t, 20, 10)
	placements := []pdfStampPlacement{
		{Page: 1, Rect: pdfStampRect{X: .25, Y: .2, Width: .5, Height: .5}, Signature: signature},
		{Page: 2, Rect: pdfStampRect{X: .25, Y: .2, Width: .5, Height: .5}, Signature: signature},
		{Page: 3, Rect: pdfStampRect{X: .25, Y: .2, Width: .5, Height: .5}, Signature: signature},
		{Page: 4, Rect: pdfStampRect{X: .25, Y: .2, Width: .5, Height: .5}, Signature: signature},
	}
	got, err := stampPDFSignatures(context.Background(), source, placements)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(source, sourceBefore) {
		t.Fatal("source PDF was modified")
	}
	if bytes.Equal(got.PDF, source) || got.PageCount != 4 || len(got.PDF) == 0 || got.SHA256 == "" {
		t.Fatalf("unexpected stamped result: pages=%d bytes=%d hash=%q", got.PageCount, len(got.PDF), got.SHA256)
	}
	if got.SHA256 != fmt.Sprintf("%x", sha256Sum(got.PDF)) {
		t.Fatal("output hash does not identify the exact generated bytes")
	}
	if err := verifyStampRaster(t, got.PDF, 1, 2, 3, 4); err != nil {
		t.Fatal(err)
	}
}

